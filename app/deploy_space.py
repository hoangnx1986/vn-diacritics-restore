"""One-time deploy of the Gradio demo to a Hugging Face Space.

This has to be run somewhere with *your* HF write credentials — an
assistant working in a sandboxed environment has no way to push to your
Hugging Face account on your behalf, which is exactly why this is a
separate manual script rather than something run automatically.

Setup:
    pip install huggingface_hub
    huggingface-cli login        # or: export HF_TOKEN=hf_...

Usage:
    python app/deploy_space.py --repo-id <your-username>/vn-diacritics-restore

This uploads a flat bundle (app.py, requirements.txt, data/dictionary.json,
data/ngram_counts.json, src/strip.py, src/baseline/*) to the Space repo.
app.py auto-detects this flat layout at runtime (see its REPO_ROOT logic).
Run `python data/build_dictionary.py` and `python src/baseline/train.py`
first if data/dictionary.json / data/ngram_counts.json don't exist yet —
they're gitignored in the main repo and not generated by this script.
"""

import argparse
from pathlib import Path

from huggingface_hub import HfApi

REPO_ROOT = Path(__file__).resolve().parent.parent

SPACE_README_TEMPLATE = """---
title: Vietnamese Diacritic Restoration
emoji: 🇻🇳
colorFrom: blue
colorTo: green
sdk: gradio
sdk_version: "{gradio_version}"
app_file: app.py
pinned: false
---

Type Vietnamese without diacritics and get them restored. n-gram +
dictionary baseline — see https://github.com/{repo_id} for eval numbers
and known limitations.
"""

FILES_TO_UPLOAD = [
    ("app.py", "app/app.py"),
    ("requirements.txt", "requirements.txt"),
    ("data/dictionary.json", "data/dictionary.json"),
    ("data/ngram_counts.json", "data/ngram_counts.json"),
    ("src/strip.py", "src/strip.py"),
    ("src/baseline/__init__.py", "src/baseline/__init__.py"),
    ("src/baseline/model.py", "src/baseline/model.py"),
    ("src/baseline/ngram.py", "src/baseline/ngram.py"),
]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-id", required=True, help="e.g. yourname/vn-diacritics-restore")
    args = parser.parse_args()

    missing = [
        REPO_ROOT / local
        for _, local in FILES_TO_UPLOAD
        if not (REPO_ROOT / local).exists()
    ]
    if missing:
        raise SystemExit(
            "Missing files, generate them first:\n"
            + "\n".join(f"  {p}" for p in missing)
        )

    import gradio

    api = HfApi()
    api.create_repo(repo_id=args.repo_id, repo_type="space", space_sdk="gradio", exist_ok=True)

    readme = SPACE_README_TEMPLATE.format(gradio_version=gradio.__version__, repo_id=args.repo_id)
    api.upload_file(
        path_or_fileobj=readme.encode("utf-8"),
        path_in_repo="README.md",
        repo_id=args.repo_id,
        repo_type="space",
    )

    for path_in_repo, local in FILES_TO_UPLOAD:
        api.upload_file(
            path_or_fileobj=str(REPO_ROOT / local),
            path_in_repo=path_in_repo,
            repo_id=args.repo_id,
            repo_type="space",
        )
        print(f"uploaded {path_in_repo}")

    print(f"\nDeployed: https://huggingface.co/spaces/{args.repo_id}")


if __name__ == "__main__":
    main()
